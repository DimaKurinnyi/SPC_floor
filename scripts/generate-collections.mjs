// Writes src/content/collections.ts: one static import per photo in public/images/collection/<name>/.
// Static imports give next/image the width, height and blur placeholder of every photo.
// Run `npm run images:collections` after adding or removing photos there.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const sourceDir = join(root, "public/images/collection");
const outFile = join(root, "src/content/collections.ts");

const byName = (a, b) => a.localeCompare(b, "en", { numeric: true });
const collections = readdirSync(sourceDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort(byName);

const imports = [];
const entries = [];

for (const collection of collections) {
  const files = readdirSync(join(sourceDir, collection))
    .filter((file) => /\.(jpe?g|png|webp)$/i.test(file))
    .sort(byName);
  const photos = files.map((file, index) => {
    const variable = `${collection}${index}`;
    imports.push(`import ${variable} from "../../public/images/collection/${collection}/${file}";`);
    return `    { code: ${JSON.stringify(file.replace(/\.[^.]+$/, ""))}, src: ${variable} },`;
  });
  entries.push(`  ${collection}: [\n${photos.join("\n")}\n  ],`);
}

const source = `// Generated by scripts/generate-collections.mjs from public/images/collection. Do not edit by hand.
import type { StaticImageData } from "next/image";

${imports.join("\n")}

/** A decor photo of a collection. The code is the file name, shown as is in every language. */
export type CollectionPhoto = { code: string; src: StaticImageData };

export const collections = {
${entries.join("\n")}
} satisfies Record<string, CollectionPhoto[]>;

export type CollectionId = keyof typeof collections;
`;

writeFileSync(outFile, source);
console.log(`Wrote ${outFile}: ${collections.length} collections, ${imports.length} photos.`);
